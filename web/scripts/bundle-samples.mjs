/**
 * Regenerate src/data/samples.ts from public/samples/*.mizan.json.
 *
 * Run after changing a sample submission, so the bundled copy the console
 * loads and the file a reader downloads cannot drift apart.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const dir = 'public/samples'
const samples = {}
for (const file of readdirSync(dir).filter((f) => f.endsWith('.mizan.json'))) {
  const record = JSON.parse(readFileSync(`${dir}/${file}`, 'utf8'))
  delete record.$schema
  delete record.mizan_submission_version
  samples[file.replace('.mizan.json', '')] = record
}

const header = `/**
 * The sample submissions, bundled.
 *
 * The same three files that sit in public/samples and that
 * scripts/export_demo_runs.py recorded its runs from. Bundling them lets the
 * console load one directly, which matters where a download cannot be
 * saved and reopened: a sandboxed viewer, a locked-down desktop, a phone.
 * The download links still serve the files themselves.
 *
 * Generated by scripts/bundle-samples.mjs. Do not edit by hand.
 */

import type { Submission } from '../lib/types'

export const SAMPLE_SUBMISSIONS: Record<string, Submission> = `

writeFileSync(
  'src/data/samples.ts',
  `${header}${JSON.stringify(samples, null, 2)} as unknown as Record<string, Submission>\n`,
)
console.log(`Bundled ${Object.keys(samples).length} sample submissions.`)
